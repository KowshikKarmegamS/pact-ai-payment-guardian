"""SQLAlchemy ORM models for PACT payment guardian."""

from datetime import datetime, timezone
import enum
import uuid
from typing import Optional
from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Enum as SQLEnum,
    Float,
    ForeignKey,
    Integer,
    Numeric,
    String,
    Text,
    JSON,
)
from sqlalchemy.orm import relationship
from app.database import Base


def utc_now() -> datetime:
    """Return current UTC timestamp with timezone."""
    return datetime.now(timezone.utc)


def as_utc(dt: Optional[datetime]) -> Optional[datetime]:
    """SQLite returns naive datetimes; PACT stores UTC, so treat naive values as UTC."""
    if dt is None:
        return None
    return dt.replace(tzinfo=timezone.utc) if dt.tzinfo is None else dt.astimezone(timezone.utc)


class ProposalStatus(str, enum.Enum):
    """Persisted lifecycle states of a payment proposal.

    Happy path:
        AWAITING_HUMAN_APPROVAL -> HUMAN_APPROVED -> AWAITING_PAYPAL_BUYER_APPROVAL
        -> PAYPAL_BUYER_APPROVED -> CAPTURE_PENDING -> CAPTURED

    PROPOSED, POLICY_PASSED and PAYPAL_ORDER_CREATED are transient stages that
    happen inside a single request; they are recorded in the audit trail rather
    than persisted as a status.

    Names equal values so the database stores readable, stable strings.
    """

    AWAITING_HUMAN_APPROVAL = "AWAITING_HUMAN_APPROVAL"
    HUMAN_APPROVED = "HUMAN_APPROVED"
    AWAITING_PAYPAL_BUYER_APPROVAL = "AWAITING_PAYPAL_BUYER_APPROVAL"
    PAYPAL_BUYER_APPROVED = "PAYPAL_BUYER_APPROVED"
    CAPTURE_PENDING = "CAPTURE_PENDING"
    CAPTURED = "CAPTURED"

    POLICY_REJECTED = "POLICY_REJECTED"
    HUMAN_REJECTED = "HUMAN_REJECTED"
    PAYPAL_CANCELLED = "PAYPAL_CANCELLED"
    PAYMENT_FAILED = "PAYMENT_FAILED"
    APPROVAL_EXPIRED = "APPROVAL_EXPIRED"


# Proposals in these states hold a claim on the mandate budget.
COMMITTED_STATUSES = (
    ProposalStatus.HUMAN_APPROVED,
    ProposalStatus.AWAITING_PAYPAL_BUYER_APPROVAL,
    ProposalStatus.PAYPAL_BUYER_APPROVED,
    ProposalStatus.CAPTURE_PENDING,
)
SPENT_STATUSES = (ProposalStatus.CAPTURED,)

# States in which a valid human approval is still in force.
APPROVED_STATUSES = (
    ProposalStatus.HUMAN_APPROVED,
    ProposalStatus.AWAITING_PAYPAL_BUYER_APPROVAL,
    ProposalStatus.PAYPAL_BUYER_APPROVED,
    ProposalStatus.PAYPAL_CANCELLED,
)


class Product(Base):
    """Catalog product available for purchase proposals."""

    __tablename__ = "products"

    id = Column(Integer, primary_key=True, autoincrement=True)
    name = Column(String(255), nullable=False)
    description = Column(Text, nullable=False, default="")
    price = Column(Numeric(10, 2, asdecimal=True), nullable=False)
    category = Column(String(100), nullable=False, index=True)
    merchant = Column(String(100), nullable=False, index=True)
    image_url = Column(String(500), nullable=True)
    in_stock = Column(Boolean, nullable=False, default=True)

    def __repr__(self) -> str:
        return f"<Product(id={self.id}, name='{self.name}', price={self.price}, merchant='{self.merchant}')>"


class Mandate(Base):
    """Spending mandate governing allowed budget, merchants, and categories."""

    __tablename__ = "mandates"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    name = Column(String(255), nullable=False)
    max_budget = Column(Numeric(10, 2, asdecimal=True), nullable=False)
    currency = Column(String(3), nullable=False, default="USD")
    allowed_merchants = Column(JSON, nullable=False, default=list)
    allowed_categories = Column(JSON, nullable=False, default=list)
    restrictions = Column(JSON, nullable=False, default=dict)
    is_active = Column(Boolean, nullable=False, default=True)
    expires_at = Column(DateTime(timezone=True), nullable=True)
    revoked_at = Column(DateTime(timezone=True), nullable=True)
    created_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)
    updated_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=utc_now,
        onupdate=utc_now,
    )

    proposals = relationship("Proposal", back_populates="mandate", cascade="all, delete-orphan")

    def __repr__(self) -> str:
        return f"<Mandate(id='{self.id}', name='{self.name}', max_budget={self.max_budget}, is_active={self.is_active})>"


class Proposal(Base):
    """Purchase proposal generated by AI, subject to deterministic policy evaluation."""

    __tablename__ = "proposals"

    id = Column(String(36), primary_key=True, default=lambda: str(uuid.uuid4()))
    mandate_id = Column(String(36), ForeignKey("mandates.id", ondelete="CASCADE"), nullable=False, index=True)
    product_id = Column(Integer, ForeignKey("products.id"), nullable=False, index=True)
    product_name = Column(String(255), nullable=False)
    merchant = Column(String(100), nullable=False)
    category = Column(String(100), nullable=False)
    price = Column(Numeric(10, 2, asdecimal=True), nullable=False)
    quantity = Column(Integer, nullable=False, default=1)
    total_amount = Column(Numeric(10, 2, asdecimal=True), nullable=False)
    currency = Column(String(3), nullable=False, default="USD")
    status = Column(
        SQLEnum(ProposalStatus, native_enum=False, length=40, create_constraint=False),
        nullable=False,
        default=ProposalStatus.AWAITING_HUMAN_APPROVAL,
        index=True,
    )
    status_reason = Column(Text, nullable=True)

    # --- AI provenance (informational only; never used for authorization) ---
    user_prompt = Column(Text, nullable=True)
    ai_reasoning = Column(Text, nullable=True)
    ai_provider = Column(String(32), nullable=True)  # "openai" | "heuristic" | "re-evaluation"
    ai_model = Column(String(100), nullable=True)
    ai_fallback_reason = Column(Text, nullable=True)
    supersedes_id = Column(String(36), nullable=True)
    alternatives = Column(JSON, nullable=True)

    # --- Deterministic policy decision ---
    policy_checks = Column(JSON, nullable=True)
    remaining_budget_at_decision = Column(Numeric(10, 2, asdecimal=True), nullable=True)
    revalidation_checks = Column(JSON, nullable=True)
    revalidated_at = Column(DateTime(timezone=True), nullable=True)

    # --- Integrity binding (fingerprint over canonical proposal + mandate policy) ---
    proposal_fingerprint = Column(String(64), nullable=True)
    approval_fingerprint = Column(String(64), nullable=True)
    approval_snapshot = Column(JSON, nullable=True)
    approved_at = Column(DateTime(timezone=True), nullable=True)

    # Legacy column kept for schema compatibility; no longer issued.
    approval_token = Column(String(255), nullable=True, unique=True, index=True)

    # --- PayPal ---
    idempotency_key = Column(
        String(255),
        nullable=False,
        unique=True,
        index=True,
        default=lambda: str(uuid.uuid4()),
    )
    paypal_order_id = Column(String(255), nullable=True, index=True)
    paypal_order_status = Column(String(40), nullable=True)
    paypal_approval_url = Column(String(500), nullable=True)
    paypal_capture_id = Column(String(255), nullable=True, index=True)
    paypal_capture_status = Column(String(40), nullable=True)
    captured_amount = Column(Numeric(10, 2, asdecimal=True), nullable=True)
    captured_currency = Column(String(3), nullable=True)
    captured_at = Column(DateTime(timezone=True), nullable=True)
    paypal_debug_id = Column(String(100), nullable=True)
    capture_lock_expires = Column(Float, nullable=True)

    created_at = Column(DateTime(timezone=True), nullable=False, default=utc_now)
    updated_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=utc_now,
        onupdate=utc_now,
    )

    mandate = relationship("Mandate", back_populates="proposals")
    product = relationship("Product")

    def __repr__(self) -> str:
        return (
            f"<Proposal(id='{self.id}', product='{self.product_name}', "
            f"total={self.total_amount}, status='{self.status}')>"
        )


class AuditLog(Base):
    """Append-only audit trail of all security, evaluation, and transaction events."""

    __tablename__ = "audit_logs"

    id = Column(Integer, primary_key=True, autoincrement=True)
    event_type = Column(String(100), nullable=False, index=True)
    entity_type = Column(String(100), nullable=False, index=True)
    entity_id = Column(String(255), nullable=False, index=True)
    details = Column(JSON, nullable=False, default=dict)
    timestamp = Column(DateTime(timezone=True), nullable=False, default=utc_now, index=True)

    def __repr__(self) -> str:
        return f"<AuditLog(id={self.id}, event='{self.event_type}', entity='{self.entity_type}:{self.entity_id}')>"
